"""Import the repository's algorithm references into ReMe's searchable digest.

The embedded AgentScope ReMe configuration intentionally watches only
``daily/`` and ``digest/``. This importer therefore materializes the source
notes and historical solutions as Markdown under one owned
``digest/wiki/algorithm-library`` subtree. ReMe's existing file watcher indexes
those files alongside conversation memories; no separate vector store or LLM
summarization pass is involved.

The import is deterministic and idempotent. A manifest lets later startups
update or remove only files previously generated by this importer, leaving all
other ReMe memory cards untouched.
"""
from __future__ import annotations

import hashlib
import json
import logging
import os
import re
import zipfile
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from typing import Iterable

from app.config import reme_workspace_dir

logger = logging.getLogger(__name__)

_SOURCE_ARCHIVE = "01-算法套路.md.zip"
_NOTES_ARCHIVE_ROOT = "04-算法与编程"
_OUTPUT_SUBTREE = Path("digest/wiki/algorithm-library")
_MANIFEST_NAME = ".source-manifest.json"
_MAX_ARCHIVE_MEMBER_BYTES = 8 * 1024 * 1024
_IMAGE_SUFFIXES = {".gif", ".jpeg", ".jpg", ".png", ".svg", ".webp"}
_SOURCE_LANGUAGE = {
    ".c": ("C", "c"),
    ".cc": ("C++", "cpp"),
    ".cpp": ("C++", "cpp"),
    ".cxx": ("C++", "cpp"),
    ".go": ("Go", "go"),
    ".h": ("C/C++", "cpp"),
    ".hpp": ("C++", "cpp"),
    ".java": ("Java", "java"),
    ".py": ("Python", "python"),
    ".rs": ("Rust", "rust"),
    ".ts": ("TypeScript", "typescript"),
}
_SOURCE_TITLE_PATTERNS = (
    re.compile(r"^\s*(?://|///|\*|#)\s*\[[^\]]+\]\s*(.+?)\s*$"),
)
_FRONTMATTER = re.compile(r"\A---\s*\r?\n(?P<yaml>.*?)\r?\n---\s*(?:\r?\n|\Z)", re.DOTALL)
_FRONTMATTER_FIELD = re.compile(r"^([A-Za-z0-9_-]+):\s*(.*?)\s*$")


@dataclass(frozen=True)
class ImportReport:
    """Summary of files written to the ReMe workspace."""

    workspace_dir: str
    notes: int = 0
    solutions: int = 0
    assets: int = 0
    written: int = 0
    unchanged: int = 0
    removed: int = 0
    skipped: bool = False


def _repository_root() -> Path:
    # algorithm_knowledge.py -> memory -> app -> agent -> backend -> repo root
    return Path(__file__).resolve().parents[4]


def _source_root(value: str | Path | None) -> Path:
    configured = value or os.getenv("ALGOCOACH_KNOWLEDGE_SOURCE_DIR")
    return Path(configured).expanduser().resolve() if configured else _repository_root()


def _yaml_string(value: str) -> str:
    # JSON's double-quoted strings are valid YAML scalars and escape newlines.
    return json.dumps(value, ensure_ascii=False)


def _frontmatter(fields: Iterable[tuple[str, str]]) -> str:
    rows = ["---"]
    rows.extend(f"{key}: {_yaml_string(value)}" for key, value in fields if value)
    rows.append("---")
    return "\n".join(rows) + "\n\n"


def _source_frontmatter(text: str) -> tuple[dict[str, str], str]:
    match = _FRONTMATTER.match(text)
    if not match:
        return {}, text
    fields: dict[str, str] = {}
    for line in match.group("yaml").splitlines():
        field = _FRONTMATTER_FIELD.match(line)
        if not field:
            continue
        key, raw = field.groups()
        raw = raw.strip()
        if raw.startswith('"'):
            try:
                value = json.loads(raw)
            except json.JSONDecodeError:
                value = raw.strip('"')
        elif raw.startswith("'") and raw.endswith("'"):
            value = raw[1:-1].replace("''", "'")
        else:
            value = raw
        if isinstance(value, str):
            fields[key] = value
    return fields, text[match.end():]


def _safe_relative_path(value: str) -> PurePosixPath | None:
    path = PurePosixPath(value)
    if path.is_absolute() or not path.parts or any(part in {"", ".", ".."} for part in path.parts):
        return None
    if "\\" in value or "\x00" in value:
        return None
    return path


def _read_archive(source_root: Path) -> tuple[dict[str, bytes], int]:
    archive_path = source_root / _SOURCE_ARCHIVE
    if not archive_path.is_file():
        raise FileNotFoundError(f"algorithm notes archive not found: {archive_path}")

    outputs: dict[str, bytes] = {}
    note_count = 0
    with zipfile.ZipFile(archive_path) as archive:
        for item in archive.infolist():
            if item.is_dir() or item.file_size > _MAX_ARCHIVE_MEMBER_BYTES:
                continue
            member = _safe_relative_path(item.filename)
            if member is None or member.parts[0] != _NOTES_ARCHIVE_ROOT:
                continue
            relative = PurePosixPath(*member.parts[1:])
            if not relative.parts:
                continue

            suffix = Path(relative.name).suffix.lower()
            if suffix == ".md":
                source_text = archive.read(item).decode("utf-8-sig")
                metadata, body = _source_frontmatter(source_text)
                title = metadata.get("title") or Path(relative.name).stem
                description = f"算法套路笔记，原始来源：{item.filename}"
                content = _frontmatter((
                    ("name", title),
                    ("description", description),
                    ("knowledge_type", "algorithm_note"),
                    ("source_path", f"{_SOURCE_ARCHIVE}::{item.filename}"),
                    ("source_date", metadata.get("date", "")),
                    ("source_lastmod", metadata.get("lastmod", "")),
                )) + f"# {title}\n\n{body.lstrip()}"
                output = PurePosixPath("notes", *relative.parts).as_posix()
                outputs[output] = content.encode("utf-8")
                note_count += 1
            elif suffix in _IMAGE_SUFFIXES:
                output = PurePosixPath("notes", *relative.parts).as_posix()
                outputs[output] = archive.read(item)

    return outputs, note_count


def _filename_title(path: Path) -> str:
    stem = path.stem
    stem = re.sub(r"^\d+\.(?=[A-Za-z\u3400-\u9fff])", "", stem)
    words = re.sub(r"[_-]+", " ", stem).replace(".", " ").split()
    title = " ".join(words)
    return title.title() if title.isascii() else title


def _source_title(text: str, fallback: str) -> str:
    for line in text.splitlines()[:80]:
        for pattern in _SOURCE_TITLE_PATTERNS:
            match = pattern.match(line)
            if match:
                candidate = match.group(1).strip()
                if candidate and not candidate.startswith("@"):
                    return candidate
    return fallback


def _fence_for(source: str) -> str:
    longest = max((len(match.group()) for match in re.finditer(r"`+", source)), default=0)
    return "`" * max(3, longest + 1)


def _read_solutions(source_root: Path) -> tuple[dict[str, bytes], int]:
    editor_root = source_root / "editor"
    if not editor_root.is_dir():
        raise FileNotFoundError(f"historical solutions directory not found: {editor_root}")

    outputs: dict[str, bytes] = {}
    solution_count = 0
    for source in sorted(editor_root.rglob("*")):
        if source.is_symlink() or not source.is_file():
            continue
        language = _SOURCE_LANGUAGE.get(source.suffix.lower())
        if language is None:
            continue
        relative = source.relative_to(editor_root)
        relative_posix = PurePosixPath(*relative.parts)
        safe_relative = _safe_relative_path(relative_posix.as_posix())
        if safe_relative is None:
            continue

        raw = source.read_text(encoding="utf-8-sig")
        if not raw.strip():
            continue
        language_name, fence_language = language
        fallback = _filename_title(source)
        title = _source_title(raw, fallback)
        template = source.stem.lower() == "template"
        kind = "code_template" if template else "historical_solution"
        description = (
            f"竞赛代码模板，语言：{language_name}。原始来源：editor/{relative_posix.as_posix()}"
            if template else
            f"历史算法题解，语言：{language_name}。原始来源：editor/{relative_posix.as_posix()}"
        )
        content = _frontmatter((
            ("name", title),
            ("description", description),
            ("knowledge_type", kind),
            ("language", language_name),
            ("source_path", f"editor/{relative_posix.as_posix()}"),
        ))
        content += (
            f"# {title}\n\n"
            f"原始题解文件：`editor/{relative_posix.as_posix()}`\n\n"
            f"## {language_name} 实现\n\n"
            f"{_fence_for(raw)}{fence_language}\n{raw.rstrip()}\n{_fence_for(raw)}\n"
        )
        output = PurePosixPath("solutions", *safe_relative.parts).as_posix() + ".md"
        outputs[output] = content.encode("utf-8")
        solution_count += 1

    return outputs, solution_count


def _read_manifest(path: Path) -> set[str]:
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return set()
    files = payload.get("files") if isinstance(payload, dict) else None
    if not isinstance(files, list):
        return set()
    return {value for value in files if isinstance(value, str)}


def _atomic_write(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.tmp")
    temporary.write_bytes(data)
    temporary.replace(path)


def _remove_stale_owned_files(target_root: Path, stale: set[str]) -> int:
    root = target_root.resolve()
    removed = 0
    for value in sorted(stale):
        relative = _safe_relative_path(value)
        if relative is None:
            continue
        path = target_root.joinpath(*relative.parts)
        if not path.is_symlink() and path.resolve().is_relative_to(root) and path.is_file():
            path.unlink()
            removed += 1
    return removed


def seed_algorithm_knowledge(
    *,
    source_dir: str | Path | None = None,
    workspace_dir: str | Path | None = None,
) -> ImportReport:
    """Materialize source notes and solutions in ReMe's searchable digest.

    Args:
        source_dir: Directory containing ``01-算法套路.md.zip`` and ``editor/``.
            Defaults to ``ALGOCOACH_KNOWLEDGE_SOURCE_DIR`` or the repository root.
        workspace_dir: ReMe workspace. Defaults to ``REME_WORKSPACE_DIR``.

    Returns:
        Counts of imported notes, solutions, assets and filesystem changes.
    """
    source_root = _source_root(source_dir)
    note_outputs, note_count = _read_archive(source_root)
    solution_outputs, solution_count = _read_solutions(source_root)
    generated = {**note_outputs, **solution_outputs}

    workspace = Path(workspace_dir or reme_workspace_dir()).expanduser().resolve()
    target_root = workspace / _OUTPUT_SUBTREE
    target_root.mkdir(parents=True, exist_ok=True)
    manifest_path = target_root / _MANIFEST_NAME
    previous = _read_manifest(manifest_path)
    current = set(generated)

    written = 0
    unchanged = 0
    for relative, content in sorted(generated.items()):
        path = target_root.joinpath(*PurePosixPath(relative).parts)
        if path.is_file() and not path.is_symlink() and path.read_bytes() == content:
            unchanged += 1
            continue
        _atomic_write(path, content)
        written += 1

    removed = _remove_stale_owned_files(target_root, previous - current)
    manifest = json.dumps(
        {"format": "algocoach-reme-algorithm-library-v1", "files": sorted(current)},
        ensure_ascii=False,
        indent=2,
    ).encode("utf-8")
    if not manifest_path.is_file() or manifest_path.read_bytes() != manifest:
        _atomic_write(manifest_path, manifest)

    report = ImportReport(
        workspace_dir=str(workspace),
        notes=note_count,
        solutions=solution_count,
        assets=len(note_outputs) - note_count,
        written=written,
        unchanged=unchanged,
        removed=removed,
    )
    logger.info(
        "ReMe algorithm library ready: notes=%d solutions=%d assets=%d "
        "written=%d unchanged=%d removed=%d path=%s",
        report.notes,
        report.solutions,
        report.assets,
        report.written,
        report.unchanged,
        report.removed,
        target_root,
    )
    return report
